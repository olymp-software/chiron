package apperr

import (
	"fmt"
	"strings"
)

//go:generate go run ./gen ../../frontend/src/errors/codes.ts

// TypeScript returns the frontend module listing every code as a union type.
func TypeScript() []byte {
	var b strings.Builder
	b.WriteString("// Code generated by internal/apperr/gen. DO NOT EDIT.\n\n")
	b.WriteString("export const errorCodes = [\n")
	for _, c := range All {
		fmt.Fprintf(&b, "  '%s',\n", c)
	}
	b.WriteString("] as const\n\n")
	b.WriteString("export type ErrorCode = (typeof errorCodes)[number]\n")
	return []byte(b.String())
}
